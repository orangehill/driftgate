// FuzzLine: Line never panics and stays fast on any command; arguments are
// split at \x01.
func FuzzLine(f *testing.F) {
	for _, s := range []string{"sh\x01-c\x01mysql -p$X 'a' \"b$(c)\" `d` <<EOF\nx\nEOF", "mysql\x01-pS3", "curl\x01-H\x01Authorization: Bearer x",
		"x\x01Server=h;Password={a;b};", "bash\x01-lc\x01a=$(b \"$(c)\") && ${D} || (e; f) > g", "x\x01{\"password\":\"a\\\"b\"}"} {
		f.Add(s)
	}
	f.Fuzz(func(t *testing.T, s string) {
		start := time.Now()
		Line(strings.Split(s, "\x01"))
		if d := time.Since(start); d > time.Second {
			t.Fatalf("%v on %d bytes", d, len(s))
		}
	})
}
